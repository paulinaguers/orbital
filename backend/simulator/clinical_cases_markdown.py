def build_markdown(rows):
    """The whole .md as text. / Todo el .md como texto."""
    days_by_id = case_days_by_id()
    parts = [HEADER, baseline_section(), "## Cases / Casos"]
    for prefix, title in GROUPS:
        parts += [f"### {title}", case_table(prefix, rows, days_by_id)]
    parts += [PVT_355_SECTION, decisions_section(rows), NEW_NAMES_SECTION, THREAD_A_SECTION, FUTURE_SECTION]
    return "\n\n".join(parts) + "\n"


def write_markdown(rows, path=OUTPUT_MD):
    """Writes the .md with LF line endings. / Escribe el .md con finales LF."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(build_markdown(rows), encoding="utf-8", newline="\n")
