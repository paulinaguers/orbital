def format_values(values):
    """Turns a case's changed columns into short text, e.g. "systolic 129, diastolic 70".
    """
    if not values:
        return "all at baseline mean"
    return ", ".join(f"{LABELS[column]} {value}{UNITS.get(column, '')}" for column, value in values.items())


def format_expected(day, row):
    """Expected "clinical → final" for each measurement under test that day.
    """
    if not day["expected"]:
        return "all green"
    parts = []
    for measurement in day["expected"]:
        clinical = row["expected_clinical_level_" + measurement]
        final = row["expected_level_" + measurement]
        parts.append(f"{measurement}: {clinical} → {final}")
    return "<br>".join(parts)


def case_days_by_id():
    """Maps each case_id to its list of days."""
    found = list(cases.NO_BASELINE_CASES) + list(cases.RADIATION_CASES)
    for group in list(cases.SINGLE_CASES.values()) + list(cases.SEQUENCE_CASES.values()):
        found.extend(group)
    return {case["case_id"]: case["days"] for case in found}


def case_table(prefix, rows, days_by_id):
    """One Markdown table with every row whose case_id starts with prefix.
    """
    lines = ["| Case | Day | Values | Expected (clinical → final) | Note |", "| --- | --- | --- | --- | --- |"]
    # A case uses consecutive rows (a test checks it), so its 1st row is its
    # day 1, its 2nd row is its day 2, and so on. "seen" counts the rows so far.
    seen = {}
    for row in rows:
        case_id = row["case_id"]
        if not case_id.startswith(prefix):
            continue
        position = seen.get(case_id, 0)
        seen[case_id] = position + 1
        day = days_by_id[case_id][position]
        lines.append(f"| {case_id} | {row['flight_day']} | {format_values(day['values'])} | "
                     f"{format_expected(day, row)} | {day['note']} |")
    return "\n".join(lines)


def baseline_section():
    """Table of the baseline design."""
    lines = [
        "## Baseline",
        "",
        "Flight days 4-10 (order shuffled with a fixed seed). Mean and `statistics.pstdev` "
        "(population standard deviation): formula proposed by thread C on 14/11/2026, to confirm "
        "with thread A.",
        "",
        "| Column | Baseline values | Mean | pstdev |",
        "| --- | --- | --- | --- |",
    ]
    for column, (mean, std_dev) in cases.BASELINE_DESIGN.items():
        values = ", ".join(str(v) for v in cases.BASELINE_DAY_VALUES[column])
        lines.append(f"| `{column}` | {values} | {mean} | {std_dev} |")
    return "\n".join(lines)


def decisions_section(rows):
    """Open decisions with how many rows wait on each one.
    """
    lines = [
        "## Open team decisions",
        "",
        "| Code | Decision | Rows waiting |",
        "| --- | --- | --- |",
    ]
    for code, text in cases.DECISIONS.items():
        # Match the whole code, so a future "Q10" does not count as "Q1".
        pattern = re.compile(re.escape(code) + r"(?![\w-])")
        waiting = sum(1 for row in rows if "PENDING" in row.values() and pattern.search(row["note"]))
        lines.append(f"| {code} | {text} | {waiting} |")
    return "\n".join(lines)


